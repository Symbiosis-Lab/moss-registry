#!/usr/bin/env bash
# Corrections the cut cannot infer, run with the working directory at site/.
# Idempotent: every step either checks before it writes or rewrites a value
# from what site/ now holds.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)

# A starter inherits the destination folder name; its home is structural.
perl -0pi -e 's/\A---\n(?!home: true\n)/---\nhome: true\n/; s/\A(---\n(?:(?!---\n).*\n)*?)title:.*\n/$1/' index.md

# The plugin is Don Ludwig's; the full site's manifest names the site instead.
python3 - <<'PY'
import json
from pathlib import Path
p = Path(".moss/plugins/projektschau/manifest.json")
m = json.loads(p.read_text(encoding="utf-8"))
m["author"] = "Don Ludwig (Projektschau for KERN, github.com/donludwig/projektschau-kern), ported to moss"
p.write_text(json.dumps(m, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
PY

# The footers credit Projektschau without its author.
perl -pi -e 's/(\[Projektschau for KERN\]\([^)]*\) 0\.1\.0) (?!by )/$1 by Don Ludwig /' footer.md
perl -pi -e 's/(\[Projektschau for KERN\]\([^)]*\) 0\.1\.0) (?!von )/$1 von Don Ludwig /' de/footer.md

# OFL 1.1 and ISC both require their notice to travel with the copies; the
# full site ships the fonts and the icons without them.
cp "$here/licences/OFL-FiraSans.txt" .moss/theme/fonts/OFL-FiraSans.txt
cp "$here/licences/LICENSE-lucide.txt" .moss/plugins/projektschau/LICENSE-lucide.txt

# A gallery picture the cut left out goes from its page with its caption line,
# and a gallery left empty goes with it.
python3 - <<'PY'
import re
from pathlib import Path
from urllib.parse import unquote
GALLERY_IMG = re.compile(r"^!\[\]\(([^)]+\.jpg)\)$")
for md in sorted(Path(".").rglob("*.md")):
    if md.parts[0] == ".moss":
        continue
    lines = md.read_text(encoding="utf-8").split("\n")
    out, i = [], 0
    while i < len(lines):
        m = GALLERY_IMG.match(lines[i])
        if m and not (md.parent / unquote(m.group(1))).is_file():
            i += 2 if i + 1 < len(lines) and lines[i + 1].startswith("*") else 1
            continue
        out.append(lines[i])
        i += 1
    text = re.sub(r"\n:::gallery[^\n]*\n:::\n\n?", "\n", "\n".join(out))
    if text != md.read_text(encoding="utf-8"):
        md.write_text(text, encoding="utf-8")
PY

