# About the sources counts pictures per holder; recount what the cut kept.
python3 - <<'PY'
import re
from collections import Counter
from pathlib import Path
from urllib.parse import unquote

HOLDERS = {"Wien Museum": "wm", "Wienbibliothek": "wb", "Austrian National Library": "onb", "Rijksmuseum": "rijks"}
IMG = re.compile(r"!\[([^\]]*)\]\(([^)]+\.jpg)\)")
seen = {}
for md in sorted(Path(".").rglob("*.md")):
    if md.parts[0] in ("de", ".moss") or md == Path("index.md"):
        continue  # the home's photograph repeats Karl-Marx-Hof's, and de/ reuses the same files
    lines = md.read_text(encoding="utf-8").splitlines()
    for i, line in enumerate(lines):
        for alt, src in IMG.findall(line):
            caption = alt or (lines[i + 1] if i + 1 < len(lines) else "")
            holder = next((h for k, h in HOLDERS.items() if k in caption), None)
            if holder is None:
                raise SystemExit(f"fixups: no holder named in the caption of {src} on {md}")
            seen.setdefault((md.parent / unquote(src)).resolve(), holder)
n = Counter(seen.values())

def plural(k, one, many):
    return f"{n[k]} {one if n[k] == 1 else many}"

for path, rows in {
    "About the sources.md": [
        ("Wien Museum online collection", "wm", "picture", "pictures"),
        ("Wienbibliothek im Rathaus, through Europeana", "wb", "picture", "pictures"),
        ("Austrian National Library, through Wikimedia Commons", "onb", "picture", "pictures"),
        ("Rijksmuseum, Amsterdam, through Wikimedia Commons", "rijks", "picture", "pictures"),
    ],
    "de/About the sources.md": [
        ("Online-Sammlung des Wien Museums", "wm", "Bild", "Bilder"),
        ("Wienbibliothek im Rathaus, über Europeana", "wb", "Bild", "Bilder"),
        ("Österreichische Nationalbibliothek, über Wikimedia Commons", "onb", "Bild", "Bilder"),
        ("Rijksmuseum, Amsterdam, über Wikimedia Commons", "rijks", "Bild", "Bilder"),
    ],
}.items():
    p = Path(path)
    text = p.read_text(encoding="utf-8")
    for label, key, one, many in rows:
        if n[key] == 0:
            raise SystemExit(f"fixups: no {key} picture kept; drop its line from {path} and the footers")
        text, k = re.subn(rf"(?m)^(- {re.escape(label)}: )\d+ \w+", lambda m: m.group(1) + plural(key, one, many), text)
        if k != 1:
            raise SystemExit(f"fixups: the '{label}' line is missing from {path}")
    p.write_text(text, encoding="utf-8")
PY

# The board's fields and the home's highlights must still point at what the cut kept.
python3 - <<'PY'
import re
from pathlib import Path
config = Path(".moss/config.toml").read_text(encoding="utf-8")
for folders in re.findall(r"(?m)^in = \[(.*)\]$", config):
    for name in re.findall(r'"([^"]+)"', folders):
        if not Path(name).is_dir():
            raise SystemExit(f"fixups: config.toml names the folder '{name}', which the cut dropped")
for home in ("index.md", "de/index.md"):
    for target in re.findall(r"\[\[([^\]]+)\]\]", Path(home).read_text(encoding="utf-8")):
        if not list(Path(".").glob(f"*/{target}.md")):
            raise SystemExit(f"fixups: {home} highlights [[{target}]], which the cut dropped")
PY
